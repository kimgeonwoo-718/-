        ),
        // '얘기'(이야기)를 '애기'(아기)로. 뒤에 '하다·나누다·듣다' 가 오면 이야기다 — '애기가 했어'(아기가)는 조사 '가' 라 안 걸리고,
        // '애기할머니'(말뭉치에 있었다)는 '할머·할아' 를 뺀다.
        TextRule.of(
            """(?<![가-힣])애기((?:를)?\s*(?:좀\s+)?)(?=(?:하자|해|했|할(?!머|아)|하고|하는|하면|하지|하던|나누|나눠|나눴|들었|들어|들은))""",
            "얘기$1",
            R
        ),

        // '결재'(윗사람의 승인)와 '결제'(돈 치르기). 앞에 치르는 수단이 오면 결제다.
        TextRule.of(
            """(카드|현금|계좌이체|핸드폰|휴대폰|폰|페이|포인트|할부|일시불)(로|으로)?(\s*)결재""",
            "$1$2$3결제",
            R
        ),

        // 뒤에 치르는 수단·돈이 와도 결제다('결재는 카드로'). '결재 완료·취소'는 사내 결재에도
        // 쓰여서 뺐다.
        TextRule.of("""결재(는|가|를|도|\s)?(\s*)(?=카드|현금|계좌|금액|수단|페이|대금|내역|오류|실패|창)""", "결제$1$2", R),

        // 병이 낫다 — 앞에 아픈 것이 오면 '낳'이 아니라 '나'다.
        TextRule.of(
            """(감기|병|상처|몸살|두통|배탈|독감|코로나|장염|비염|목감기)(가|이|는|은|도)?(\s+)((?:다|좀|많이|거의|벌써|이제|금방|싹|완전히|이미|빨리)\s+)?낳(았|아|으)""",
            "$1$2$3$4나$5",
            R
        ),

        // '이따가'(조금 뒤에)를 '있다가'로 적는 일. 문장 첫머리에서 뒤에 만남·연락이
        // 올 때만 고친다. '집에 있다가 나왔어'(머물다)는 앞에 말이 있어서 안 걸린다.
        TextRule.of(
            """^있다가(\s+)(?=(보자|봐|봬|만나|연락|전화|얘기|갈게|올게|할게))""",
            "이따가$1",
            R
        ),

        TextRule.of("""돼지(\s*)않""", "되지 않", R),
        // '안 돼지'(되지 — 짐승 '돼지' 가 아니다). 부사 '안' 바로 뒤의 '돼지' 는 언제나 '되지' 다(2026-10-13).
        TextRule.of("""(?<![가-힣])안(\s*)돼지(?=$|[^가-힣]|요|만|는|도)""", "안 되지", R),
        // 글머리·문장 첫머리의 '그런대' 는 접속 부사 '그런데' 다 — 들은 말 '그런대'(그렇다고 한다)는 문장 끝에 온다.
        TextRule.of("""(^|[.!?]\s*)그런대(?=\s|,)""", "$1그런데", R),
        // '-은대' 로 끝나는 어절은 '-은데' 다 — 그림씨의 들은 말은 '좋대'(좋다고 한다)라 '-은대' 꼴이 없다.
        TextRule.of("""([가-힣])은대(?=$|요|[^가-힣])""", "$1은데", R),
        // 글머리의 '되려' 는 '되레'(오히려) — '의사가 되려 한다'(되다 + 려)는 앞에 말이 온다.
        TextRule.of("""(^|[.!?,]\s*)되려(\s+)(?!하|고|면|는)""", "$1되레$2", R),
        TextRule.of("""몇\s+일(?!요)""", "며칠", R),

        // '낳다'(아이를 낳다)와 '낫다'(병이 낫다)는 뜻이 달라 낱말만으로는 못 가린다.
        // 다만 '빨리/얼른/어서 낳으세요' 는 쾌유를 비는 말이 굳어진 자리라 거의 언제나
        // '나으세요' 다. 부사가 앞에 붙은 이 꼴만 고친다.
        TextRule.of("""(빨리|얼른|어서|어여|속히)(\s*)낳(으|아|았)""", "$1$2나$3", R),

        // ── 자주 틀리는 것 (전쟁 시험지 2026-10-13). 큰 말뭉치(58만 줄)에서 고친 곳을 하나씩 보고 넣었다. ──────────────────────

        // '그리고 나서' 는 '그러고 나서'다 — 접속 부사 '그리고' 뒤에는 보조용언 '나다' 가 못 온다(국립국어원).
        // '나서는 사람이 없었다'(나서다)와 '나서서' 를 피해 '나서' 로 끝나거나 '나서야' 일 때만.
        TextRule.of("""(?<![가-힣])그리고(\s*)나서(?=$|[^가-힣]|야(?![가-힣]))""", "그러고 나서", R),

        // '-(으)ㄴ 채로'(그 상태 그대로)를 '체로' 로. 띄어 친 것만 본다 — '단체로·전체로' 는 한 낱말이다.
        // '고운 체로 거른다'(가루 거르는 연장)를 피해 그림씨와 거르는 말은 뺀다.
        TextRule.of(
            """(?<![가-힣])([가-힣]*[가-힣])(\s+)체로(?![가-힣])(?!\s*(?:거르|걸러|걸렀|쳐|쳤|치|내려|내리|받쳐))""",
            "$1$2채로",
            R
        ) { match ->
            val word = match.groupValues[1]
            val last = word.last()
            Hangul.jongseongOf(last) == 'ㄴ' && last != '는' && word !in SIEVE_ADJECTIVES
        },
        TextRule.of("""([가-힣]은)체로(?![가-힣])""", "$1 채로", R),

        // '몹쓸 짓'(악독한)을 '못쓸·못 쓸' 로. 뒤에 '짓·병·놈' 이 올 때만 — '못 쓸 거야'(쓸 수 없다)는 그대로다.
        TextRule.of("""(?<![가-힣])못\s?쓸(\s+)(?=(?:짓|병|놈|년|인간|녀석)(?:$|[^가-힣]|[을이은도만에들]))""", "몹쓸$1", R),

        // '-ㄹ는지'(갈는지·될는지)를 '-ㄹ런지' 로. 'ㄹ' 받침 뒤 '런지' 는 다른 말이 없다(말뭉치 4곳 다 틀린 것).
        TextRule.of("""([가-힣])런지""", "$1는지", R) { match -> Hangul.jongseongOf(match.groupValues[1][0]) == 'ㄹ' },

        // '-(으)려야'(떼려야 뗄 수 없는)를 '-ㄹ래야' 로. 뒤에 '-ㄹ 수 없다' 가 올 때만 — '아기를 달래야 할 때' 를 피한다.
        TextRule.computed("""(?<![가-힣])([가-힣]*)([가-힣])래야(?=\s+[가-힣]+\s*수(?:가|도|는)?\s*(?:없|있))""", R) { match ->
            val stem = match.groupValues[1]
            val syllable = match.groupValues[2][0]
            when {
                Hangul.jongseongOf(syllable) != 'ㄹ' -> null
                syllable == '을' -> stem + "으려야"
                else -> stem + withoutJongseong(syllable) + "려야"
            }
        },

        // '이 자리를 빌려'(빌리다)를 '빌어' 로. '빌다' 는 바라거나 비는 것('용서를 빌어')이라 빌려 쓰는 것과 갈린다.
        TextRule.of("""((?:자리|기회|지면|힘|손|이름|말|말씀|글|틈|도움|권위|입)(?:을|를)\s*)빌어(?=서|$|[^가-힣])""", "$1빌려", R),

        // '염두에 두다' 를 '염두해 두다' 로. '염두하다' 는 없는 말이다.
        TextRule.of("""염두해\s*(두|둬|뒀|둔|둘)""", "염두에 $1", R),

        // '열심히' 를 '열심이' 로. '열심이 대단하다'(열심 + 이)를 피해 뒤에 하는 일이 올 때만.
        TextRule.of("""(?<![가-힣])열심이(\s+)(?=(?:공부|일|하|해|했|할|한|살|노력|준비|연습|운동|뛰|달리|달려|만들|읽|쓰|써|배우|배워|가르|모으|모아|저축|다니|다녀|일하|일해|벌|키우|키워|응원|기도|청소|싸우|싸워))""", "열심히$1", R),

        // '-든지'(고르는 말)를 '-던지'(지난 일)로. 앞에 '뭘·어디·누가·언제' 가 있고 뒤가 '상관없다·알아서' 처럼 고르는 말일 때만.
        // '얼마나 춥던지'·'누가 오던지 기억이 안 나'(지난 일을 떠올림)는 그대로다.
        TextRule.of(
            """((?:뭘|뭐|무엇을|어디|어디를|어디에|어디서|어디로|누가|누구를|누구랑|언제)\s+(?:[가-힣]+\s+)?[가-힣]*[가-힣])던지(?=(?:\s*간에|\s+(?:상관|괜찮|알아서|맘대로|마음대로|관계없|난|나는|응원|다\s|뭐든)))""",
            "$1든지",
            R
        ) { match ->
            val head = match.groupValues[1]
            Hangul.jongseongOf(head.last()) != 'ㅆ' && RECALL_WORDS.none { head.contains(it) }
        },

        // '밤을 새우다'(잠을 안 자다)를 '세우다' 로. '밤을 세다'(밤을 세다 — 셈)는 쓸 일이 없다.
        TextRule.of("""(?<![가-힣])(밤(?:을)?\s*)세(웠|워|우|운|울)""", "$1새$2", R),

        // '-ㄹ게요'(다짐)를 띄어 친 '할 게요·갈 께요'. 문장 끝의 '게요' 는 어미다 — '할 게 없어'(것이)는 '게' 뒤에 말이 이어진다.
        TextRule.of("""([가-힣])\s+[게께]요(?=$|[^가-힣])""", "$1게요", R) { match -> Hangul.jongseongOf(match.groupValues[1][0]) == 'ㄹ' },

        // '비로소' 를 '비로서' 로. '황제의 비로서'(妃 + 로서)를 피해 앞이 '-의' 면 안 본다.
        TextRule.of("""(?<![가-힣])(?<!의\s)비로서(?![가-힣])""", "비로소", R)
    ) + ConfusableRules.RULES

    /** '-든지' 고칠 때 피할, 지난 일을 떠올리는 말('얼마나 춥던지', '그렇게 울던지'). */
    private val RECALL_WORDS = listOf("그렇게", "얼마나", "어찌나", "너무", "정말", "진짜", "엄청")

    /** '고운 체로 거른다' 처럼 '체'(연장)를 꾸미는 그림씨. */
    private val SIEVE_ADJECTIVES = setOf("고운", "가는", "촘촘한", "굵은", "작은", "큰", "둥근", "넓은", "좁은", "성긴", "가느다란")

    /** 받침을 뗀 음절('뗄' → '떼'). */
    private fun withoutJongseong(syllable: Char): Char =
        Hangul.decompose(syllable)?.let { Hangul.compose(it.first, it.second, 0) } ?: syllable
}
