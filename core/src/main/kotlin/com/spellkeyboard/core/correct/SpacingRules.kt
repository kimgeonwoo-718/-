    /**
     * 조사로도 쓰이는 의존명사('만큼'·'뿐')에 쓰는 **좁은** 판정.
     *
     * 관형사형 어미 '-는'·'-은'이거나 받침이 ㄹ 일 때만 참이다. 받침 ㄴ 을 통째로
     * 받아 주면 '돈만큼'·'사람뿐' 같은 조사 자리를 갈라 버린다 — 조사일 때는 붙여
     * 쓰는 것이 맞으므로 그건 오교정이다.
     */
    private fun adnominalStrict(match: MatchResult): Boolean {
        val syllable = match.groupValues[1][0]
        return syllable == '는' || syllable == '은' || Hangul.jongseongOf(syllable) == 'ㄹ'
    }

    /**
     * '만큼'·'뿐' 전용으로 더 좁힌 판정. '-는'·'-은'이거나, 받침 ㄹ 이면 **용언의 관형형으로 흔한
     * 음절**('을'·'할'·'갈' …)일 때만. 받침 ㄹ 인 명사('명절뿐만'·'서울만큼')는 조사 자리라
     * 붙여 써야 한다 — 격식체 시험지에서 '명절 뿐만'이 나왔다.
     */
    private fun adnominalVerbStrict(match: MatchResult): Boolean {
        val syllable = match.groupValues[1][0]
        return syllable == '는' || syllable == '은' || syllable in RIEUL_VERB_ADNOMINALS
    }

    private val RIEUL_VERB_ADNOMINALS = setOf('을', '할', '갈', '볼', '될', '올', '줄', '쓸', '놀', '잘', '살', '알')

