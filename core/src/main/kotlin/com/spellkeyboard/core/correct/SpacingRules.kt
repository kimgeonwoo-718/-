    private fun jiNoun(prefix: String, syllable: Char): Boolean {
        val tail = "${syllable}지"
        if (tail in JI_NOUNS) return true
        if (prefix.isEmpty()) return tail in JI_NAMES || tail in JI_SHORT_NOUNS
        return prefix.length == 1 && prefix[0] in SURNAMES && tail in JI_NAMES
    }

