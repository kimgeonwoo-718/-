        // 들어앉은 것을 수로 읽으면 '무한대로'가 '무한 대로'가 되고 '주십시오'가
        // '주십 시오'가 된다. 앞말이 붙어 있는 진짜 수량('책두 권')은 놓치지만,
        // 그건 디코더가 먼저 '책|두'를 가르면 이 규칙에 다시 걸린다.
        // **앞이 아라비아 숫자여도 안 본다.** '5천원'·'3백명' 의 '천·백' 은 숫자로 적은 수의 일부고, 숫자와 어울려
        // 쓰는 단위는 붙여 써도 된다(한글 맞춤법 제43항 다만). '5천원' 을 '5천 원' 으로 떼면서 '3만원' 은 그대로 두던
        // 들쭉날쭉함도 같이 없어진다(2026-10-11, '3개 → 3 개' 제보를 넓게 시험하다 찾음).
        // **뒤에 이어지는 글자까지 본다**(2026-10-13, 규칙 감사). 수 + 단위로 읽혀도 실은 한 낱말인 것이 기사에 흔했다 —
        // '천명했다'(밝히다) → '천 명했다', '한시적' → '한 시적', '세분화' → '세 분화', '백년대계', '십분 활용', '천벌', '열통'.
        TextRule.of(
            """(?<![가-힣0-9])(${NUMERALS.joinToString("|")})(${UNITS.joinToString("|")})(?=([가-힣]*)\s*([가-힣]*))""",
            "$1 $2",
            R
        ) { match -> match.value !in NUMERAL_EXCEPTIONS && !numeralCompound(match) },
        TextRule.of("""(?<![가-힣])한대(?=\s+[가-힣]|가|를|씩|만|에|도|정도|쯤|째)""", "한 대", R),

        // 보조용언 '-고 있다', '-지 않다/못하다/말다' 는 띄어 쓴다.
        // ("알고있다" -> "알고 있다", "쉽지않습니다" -> "쉽지 않습니다")
        TextRule.of("""([가-힣]고)(있|없|싶)""", "$1 $2", R),
        TextRule.of(
            """([가-힣]지)(않|못하|말고|말자|맙|마라|마세|말아|마(?![가-힣]))""",
            "$1 $2",
            R
        ) { match -> match.groupValues[1] !in JI_EXCEPTIONS },

        // 조사만 홀로 떨어져 나온 경우 앞말에 붙인다. ("학교 에서" -> "학교에서")
        // '와/과'는 명령형 '와'와, '밖에'는 명사 '밖'과 겹쳐서 뺐다.
        TextRule.of(
            """([가-힣])\s+(${PARTICLES.joinToString("|")})(?![가-힣])""",
            "$1$2",
            R
        ),

        // 서술격 조사 '이다' 가 홀로 떨어진 것도 앞말에 붙인다. ("김건우 입니다" -> "김건우입니다")
        // 위 조사 규칙은 언어모델이 붙인 꼴을 아는 말('학생입니다')만 고쳐졌다 — 사람 이름처럼 모델이 모르는
        // 앞말은 그대로 남았다(2026-10-03 사용자 제보). '입니다' 따위가 혼자 서는 띄어쓰기는 맞는 경우가 없어서
        // 앞말을 몰라도 붙인다. 받침 없는 말 뒤의 '이에요·이었-' 은 줄어든 꼴로 ('김건우예요', '김건우였어요').
        TextRule.computed(
            """([가-힣])\s+(${COPULAS.joinToString("|")})(?![가-힣])""",
            R
        ) { match ->
            val before = match.groupValues[1]
            val copula = match.groupValues[2]
            val open = !Hangul.hasJongseong(before[0])
            before + if (open) COPULA_AFTER_VOWEL[copula] ?: copula else copula
        },

        // 의존명사 '수': 앞은 관형형 어미 ㄹ, 뒤는 '있/없'일 때만 띄운다.
        TextRule.of("""([가-힣])\s*수\s*밖에""", "$1 수밖에", R) { match ->
            rieulBefore(match) && (match.groupValues[1] + "수") !in SU_EXCEPTIONS
        },
        TextRule.of("""([가-힣])\s*수\s*(있|없)""", "$1 수 $2", R) { match ->
            rieulBefore(match) && (match.groupValues[1] + "수") !in SU_EXCEPTIONS
        },
        // '할 수도 있어'·'갈 수는 없어'. 조사가 끼어도 같다.
        TextRule.of("""([가-힣])\s*수(도|는|조차|만)\s*(있|없)""", "$1 수$2 $3", R) { match ->
            rieulBefore(match) && (match.groupValues[1] + "수") !in SU_EXCEPTIONS
        },

        // 의존명사 '것'
        TextRule.of("""([가-힣])\s*것\s*같""", "$1 것 같", R) { match ->
            adnominalBefore(match) && (match.groupValues[1] + "것") !in GEOT_EXCEPTIONS
        },
        TextRule.of(
            """([가-힣])\s*것\s*(이다|이라|인가|일까|이야|입니다)""",
            "$1 것$2",
            R
        ) { match ->
            adnominalBefore(match) && (match.groupValues[1] + "것") !in GEOT_EXCEPTIONS
        },

        // 의존명사 '줄' ("할줄알아" -> "할 줄 알아")
        // '모르다'는 활용형이 갈려서('몰랐다') 어간만으로는 잡히지 않는다.
        TextRule.of(
            """([가-힣])\s*줄\s*(알|몰라|몰랐|모르|모른|모를)""",
            "$1 줄 $2",
            R,
            ::adnominalBefore
        ),

        // 의존명사 '둥' ("듣는둥마는둥" -> "듣는 둥 마는 둥")
        //
        // 언어모델이 '듣는둥'·'마는둥'을 **한 낱말로 알고 있어서** 디코더가 여기서 멈춘다.
        // 말뭉치에 붙여 쓴 형태가 그대로 들어가 있는 탓이다. 그래서 규칙으로 뗀다.
        //
        // **짝을 요구한다.** 이 말은 늘 '-는 둥 마는 둥' 처럼 둘이 붙어 다니고, '둥'으로
        // 끝나는 낱말이 잇달아 두 번 나오는 일은 이 관용구 말고는 없다. 앞이 관형형
        // 어미(받침 ㄹ/ㄴ)인 것까지 보면 규칙이 걸릴 자리가 사실상 이것뿐이 된다.
        //
        // 뒤에 '하다'가 붙는 꼴("...마는둥했다")을 먼저 놓는다. 나중 규칙이 같은 자리를
        // 다시 만나도 이미 띄어져 있어 결과가 바뀌지 않는다.
        TextRule.of(
            """([가-힣])\s*둥\s*(마는|말|만)\s*둥\s*(하|했|한|할)""",
            "$1 둥 $2 둥 $3",
            R,
            ::adnominalBefore
        ),
        TextRule.of(
            """([가-힣])\s*둥\s*(마는|말|만)\s*둥""",
            "$1 둥 $2 둥",
            R,
            ::adnominalBefore
        ),

        // ── 의존명사 ──────────────────────────────────────────────────────────
        //
        // 관형사형 어미(받침 ㄹ/ㄴ) 뒤의 의존명사는 띄어 쓴다. 통계로는 잘 안 되는
        // 자리다 — 말뭉치에 붙여 쓴 꼴이 그대로 들어 있어서 언어모델이 '할거야'를
        // 한 낱말로 알고 있고, 그러면 디코더가 거기서 멈춘다.
        //
        // 조건을 좁게 잡는 방식은 위의 '수'·'것'과 같다. 앞의 받침만 보지 않고
        // **뒤에 오는 것까지** 본다. 그래야 '-는데'(어미)와 '데'(의존명사)처럼
        // 겉모양이 같은 둘을 가를 수 있다.

        // '거' (것의 구어형). 뒤에 오는 말을 한정한다 — '볼거리'·'먹거리'를 피한다.
        TextRule.of("""([가-힣])거(야|예요|에요|였|였어|거든)""", "$1 거$2", R, ::adnominalBefore),

        // '게' (것이). '-ㄹ게'(어미)와 갈리려고 뒤에 오는 서술어를 요구한다.
        // '할게요'는 뒤가 '요'라 안 걸리고, '먹을 게 없어'는 걸린다.
        TextRule.of("""([가-힣])\s*게\s*(없|있|많|좋|아니|어때)""", "$1 게 $2", R, ::adnominalBefore),

        // '건지/건가' (것인지). '사건지'·'조건지' 같은 명사는 예외로 뺀다.
        TextRule.of("""([가-힣])건(지|가)""", "$1 건$2", R) { match ->
            adnominalBefore(match) && head(match) !in GEON_EXCEPTIONS
        },

        // '데' (곳·일). **조사가 붙었을 때만** 띄운다 — 조사를 못 받는 '-는데'(어미)와
        // 그것 하나로 갈린다. '그런데가'는 접속부사라 뒤돌아보기로 뺀다.
        // '여러 군데가', '가운데를' 은 한 낱말이다 — 기사 말뭉치에서 이 규칙이 고친 262곳 중 255곳이 그것이었다(2026-10-13).
        TextRule.of("""([가-힣])(?<!그런)(?<!이런)(?<!저런)(?<!가운)(?<!군)데(가|를)(?![가-힣])""", "$1 데$2", R, ::adnominalBefore),

        // '지' (그때부터 지금까지). 뒤에 기간을 재는 말이 올 때만.
        // **'-지' 로 끝나는 명사와 이름을 뺀다**(2026-10-13) — '단지 몇 개', '반지 얼마야', '현지 몇 곳', '편지 몇 통', '은지 몇 살' 을
        // '단 지·반 지' 로 갈랐다. 기사 말뭉치에서 이 규칙이 고친 405곳의 절반 넘게 그것이었다. '몇'·숫자 뒤는 때를 재는 단위일 때만.
        //
        // **기간 뒤에 '됐다·지났다·넘었다·만에·째' 처럼 시간이 흘렀다는 말이 와야 한다**(2026-10-13). 그 말이 없으면 묻는 '-ㄴ지' 다 —
        // '그게 뭔지 한참 생각했어'·'어떤지 5분 동안 고민했어'·'무엇인지 몇 년간 고민했다' 를 '뭔 지·어떤 지' 로 갈랐다.
        // '-는지·-인지·-던지' 와 그림씨('좋은지·피곤한지')도 늘 묻는 말이라 뺀다. '일 년·두 달' 처럼 한글로 쓴 수도 받는다
        // ('이해·구분·오해' 가 '이 해·구 분' 으로 읽히지 않게 한자어 수는 띄어 쓴 것과 '년·개월·주일' 만).
        TextRule.of(
            """(?<![가-힣])([가-힣]*)([가-힣])지(?=(\s*(?:$JI_SPAN)[^\n]{0,12}))""",
            "$1$2 지",
            R
        ) { match -> elapsedJi(match) },

        // '먹을것 좀·볼것이 없다' — 'ㄹ' 관형형 뒤의 '것' 은 띄운다. '날것·별것·들것·탈것'(한 낱말)을 피해 흔한 용언 꼴만(2026-10-13).
        TextRule.of("""(?<![가-힣])([가-힣]*[을할갈볼될올줄쓸잘살칠팔찰낼걸럴])것(?=$|[^가-힣]|은|이|을|도|만|좀)""", "$1 것", R),

        // '만큼'·'뿐'. 조사로도 쓰이는 말이라 좁은 판정을 쓴다.
        TextRule.of("""([가-힣])만큼""", "$1 만큼", R, ::adnominalVerbStrict),
        TextRule.of("""([가-힣])뿐(?=이|만|[^가-힣]|${'$'})""", "$1 뿐", R, ::adnominalVerbStrict),

        // '바' (앞에서 말한 내용). 조사가 붙고, 그 뒤가 끊길 때만 — '물바가지'를 피한다.
        // '알바를'(아르바이트)은 한 낱말이다. 앞 음절은 흔한 관형형만 받는다(2026-10-13) — '실바·엘바·멜바'(외국 이름)를
        // '실 바가' 로 갈랐다(기사 말뭉치 24곳의 대부분).
        TextRule.of("""([가-힣])바(가|를|에|와)(?![가-힣])""", "$1 바$2", R) { match ->
            adnominalBefore(match) && head(match) != "알바" && match.groupValues[1][0] in BA_ADNOMINALS
        },

        // '채' (그 상태 그대로). '입은 채로'.
        TextRule.of("""([가-힣])채로(?![가-힣])""", "$1 채로", R) { match ->
            Hangul.jongseongOf(match.groupValues[1][0]) == 'ㄴ' && head(match) !in CHAE_NOUNS
        },

        // '척'·'체' (그런 듯이 꾸미는 것).
        // '단체도·전체도·연체하·친척도·진척도' 는 한 낱말이다 — 기사 말뭉치에서 이 규칙이 고친 47곳이 거의 다 그것이었다(2026-10-13).
        TextRule.of("""([가-힣])(척|체)(하|도|만)""", "$1 $2$3", R) { match ->
            adnominalBefore(match) && head(match) !in CHEOK_NOUNS && !(head(match) == "인척" && match.groupValues[3] != "하")
        },

        // '리' (까닭·이치). 용언 '빨리·멀리'와 겹쳐서 예외표가 길다.
        //
        // **'-리는'은 받지 않는다.** '열리는'·'걸리는'·'팔리는'처럼 피동 용언의 활용형이
        // 통째로 그 꼴이라, 조사 '는'까지 받아 주면 얻는 것보다 잃는 것이 많다
        // ('격주로 열리는' → '격주로 열 리는').
        //
        // **'ㄹ리' 로 끝나는 외래어·이름이 많다** — '젤리·브로콜리·켈리·설리·빌리·폴리·밸리·랠리·줄리', 그리고 '일리가 있다'. 기사
        // 말뭉치에서 이 규칙이 고친 195곳이 거의 다 그것이었다(2026-10-13). 그래서 앞 음절을 용언의 관형형으로 흔한 것만 받고,
        // 두 음절 어절('할리가')은 뒤에 '없다·있나·만무' 나 문장 끝이 와야 고친다.
        TextRule.of("""(?<![가-힣])([가-힣]*)([가-힣])리(가|도)(?![가-힣])(?=(\s*[가-힣?!.~]*))""", "$1$2 리$3", R) { match ->
            riNoun(match)
        },

        // '뻔하다' (그렇게 될 것 같았다). '뻔'으로 끝나는 말이 없어 안전하다.
        TextRule.of("""([가-힣])뻔(하|했|한)""", "$1 뻔$2", R, ::rieulBefore),

        // '-ㄴ 김에'(어떤 일을 하는 기회에) — '온김에 → 온 김에'. '홧김·술김·입김' 은 받침이 ㄴ 이 아니라 안 걸리고, '내친김에' 는 한 낱말이다(2026-10-14).
        TextRule.of("""(?<![가-힣])([가-힣]*)([가-힣])김에(?=$|[^가-힣])""", "$1$2 김에", R) { match ->
            Hangul.jongseongOf(match.groupValues[2][0]) == 'ㄴ' && !match.value.startsWith("내친")
        },

        // '만하다' (그럴 값어치가 있다). '일만 하고'와 겹쳐서 예외표를 본다.
        // '만'과 '해' 사이가 띄어 와도 받는다 — 언어모델이 '먹을만'을 한 낱말로 알고 있어서
        // 디코더가 '먹을만 해'로 끊어 낸다.
        TextRule.of("""([가-힣])만\s*(하|한|해|했|함)""", "$1 만$2", R) { match ->
            rieulBefore(match) && head(match) !in MANHA_EXCEPTIONS
        },

        // '중' (하는 동안). 좁은 판정 — '집중이'·'명중을'을 건드리지 않는다.
        TextRule.of("""([가-힣])중(이|인|에|을|은)""", "$1 중$2", R) { match ->
            adnominalStrict(match) && head(match) !in setOf("열중", "졸중", "필중")
        },
        // 어절이 '-는중'으로 끝날 때('밥먹는중'). 받침 ㄹ 쪽은 '월중'·'일중' 같은 명사가 있어
        // '는/은' 만 받는다.
        TextRule.of("""([는은])중(?![가-힣])""", "$1 중", R),

        // '듯' 짝 ('올 듯 말 듯'). '둥'과 같은 이유로 짝을 요구한다.
        TextRule.of("""([가-힣])\s*듯\s*(말|안)\s*듯""", "$1 듯 $2 듯", R, ::adnominalBefore),

        // '대로' (그와 같이). 조사로도 쓰여서 예외표를 본다 — '맘대로'는 붙여 쓴다.
        // 받침 ㄹ 은 **용언의 관형형으로 흔한 음절만** — '사실대로·비율대로·색깔대로·골대로·일대로'(명사 + 조사 '대로')를
        // '사실 대로' 로 갈랐다(규칙 감사 2026-10-13).
        TextRule.of("""([가-힣])대로(?![가-힣])""", "$1 대로", R) { match ->
            val syllable = match.groupValues[1][0]
            adnominalStrict(match) && head(match) !in DAERO_EXCEPTIONS &&
                (syllable == '는' || syllable == '은' || syllable in DAERO_RIEUL_VERBS)
        },

        // 부사 '좀'. 앞뒤 어느 쪽에 붙어 와도 뗀다.
