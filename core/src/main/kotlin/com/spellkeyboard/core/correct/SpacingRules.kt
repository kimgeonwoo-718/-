package com.spellkeyboard.core.correct

import com.spellkeyboard.core.hangul.Hangul

/**
 * 띄어쓰기 규칙 모음. 어절 경계를 넘나들어야 하므로 전체 창 문자열에 적용한다.
 *
 * ## 이 규칙들이 못 하는 일
 *
 * 여기 있는 것은 **특정 패턴을 고치는 규칙**이지 일반적인 띄어쓰기 복원이 아니다.
 * "제가할게요" 같이 통째로 붙여 쓴 문장을 나누려면 형태소 분석이나 문자 단위 모델이
 * 필요하다. 규칙만으로 그걸 하려 들면 오교정이 폭발한다. 모델은 다음 단계다.
 *
 * 그래서 조건을 일부러 좁게 잡았다. 의존명사는 앞의 관형형 어미(받침 ㄹ/ㄴ)와
 * 뒤에 오는 서술어를 **둘 다** 확인한 뒤에만 띄운다. '실수 있다' 같은 오교정을
 * 만들지 않기 위해서다.
 */
object SpacingRules {

    private const val R = "띄어쓰기"

    /** 관형형 어미의 받침. 이 받침이 앞에 있을 때만 뒤 의존명사를 띄운다. */
    private val ADNOMINAL_JONG = setOf('ㄹ', 'ㄴ')

    /** 받침이 ㄹ 이지만 의존명사 '수'가 아닌 명사들. */
    private val SU_EXCEPTIONS = setOf("별수", "실수", "홀수", "술수")

    /** 받침이 ㄹ/ㄴ 이지만 의존명사 '것'이 아닌 합성어들. */
    private val GEOT_EXCEPTIONS = setOf("별것", "날것", "들것")

    /** 한 단어로 붙여 쓰는 '때'들. */
    private val TTAE_EXCEPTIONS = setOf("한때", "물때", "본때")

    /**
     * 수관형사. 뒤에 단위 의존명사가 오면 띄어 쓴다 ('네 개', '두 명', '몇 번').
     * 긴 것부터 놓아야 '다섯'이 '섯'으로 잘리지 않는다.
     */
    private val NUMERALS = listOf(
        "여러", "다섯", "여섯", "일곱", "여덟", "아홉", "스무", "스물",
        "서른", "마흔", "예순", "일흔", "여든", "아흔", "쉰",
        // 한자 수사. 홑자('이','삼','오')는 뺐다 — '이분'·'삼시'처럼 딴 말과 너무 겹친다.
        "이십", "삼십", "사십", "오십", "육십", "칠십", "팔십", "구십", "십", "백", "천",
        "열", "몇", "한", "두", "세", "네"
    )

    /**
     * 단위 의존명사. 앞의 수관형사와 반드시 띄어 쓴다.
     *
     * 짧은 것 위주로 골랐다. 남는 충돌은 [NUMERAL_EXCEPTIONS] 가 걸러낸다.
     */
    private val UNITS = listOf(
        "켤레", "그루", "송이", "자루", "개월", "학년",
        "마리", "가지", "군데", "시간", "사람",
        "개", "명", "번", "살", "권", "장", "대", "잔", "병", "통", "채", "칸", "척", "알",
        // 시각·시간·돈. 구어체에서 제일 자주 나오고, 붙여 쓰면 제일 눈에 띈다.
        "시", "분", "초", "원", "달", "곳", "줄", "벌", "끼"
    )

    /**
     * 수관형사 + 단위로 읽히지만 실은 한 낱말인 것들.
     *
     * 이 표가 이 규칙의 안전장치다. '두통'을 '두 통'으로, '열대'를 '열 대'로 만드는 것이
     * 이 규칙이 낼 수 있는 가장 나쁜 실수라서, 부딪히는 것을 미리 적어 둔다.
     * '한번'은 부사('한번 해 보자')와 수량('한 번만')이 둘 다 맞아 아예 손대지 않는다.
     */
    private val NUMERAL_EXCEPTIONS = setOf(
        // **진짜 낱말만 남긴다.** 예전에는 '한개'·'세번'·'두장'처럼 낱말이 아닌 것까지
        // 들어 있어서, 정작 띄어야 할 '사과 세 개'·'두 번 다시'를 규칙이 막고 있었다.
        // 한통(한통속) · 한살(한살이) · 한잔(한잔하다)은 뒤에 붙는 말까지 봐야 갈리는데,
        // 값싼 규칙으로는 못 가리므로 붙여 두는 쪽을 골랐다.
        "한번", "한통", "한살", "한잔",
        "두통", "두상", "두목",
        "세상", "세대", "세계", "세월", "세면", "세척",
        "네발", "네모", "네온",
        "열대", "열병", "열사",
        // 수를 적을 때는 만 단위로 띄우므로 '몇백만' 은 붙여 쓴다.
        "몇백", "몇천", "몇억", "몇조",
        "몇몇", "여러분", "스무고개",
        // 넓힌 수사·단위와 부딪히는 것들. 왼쪽이 수관형사로 보이지만 한 낱말이다.
        //
        // '십시' 가 제일 중요하다 — '주십시오'·'하십시오' 가 '주십 시오' 가 된다.
        // 격식체에서 한 문장 걸러 한 번 나오는 꼴이라, 이 한 줄이 없으면 규칙 전체가
        // 손해다.
        "십시", "천장", "백분", "천분", "한곳", "한벌", "세벌"
    )

    /**
     * 앞말과 붙여 써야 하는 조사. 긴 것부터 놓아야 '에서'가 '에'로 잘리지 않는다.
     * '만'은 뺐다 — '준 만 달러', '삼 만 명'처럼 수사 '만(萬)'이 홀로 서는 일이 잦다.
     */
    /**
     * '-지 않다'로 보이지만 한 낱말인 것들. '머지않아'(오래지 않아)가 대표다 —
     * 여기서 띄우면 없는 말('머지')이 생긴다.
     */
    private val JI_EXCEPTIONS = setOf("머지", "오래지", "적지", "멀지")

    private val PARTICLES = listOf(
        "이라고", "라고", "에게서", "에게", "에서", "께서", "으로",
        "부터", "까지", "마다", "조차", "처럼",
        "은", "는", "을", "를", "에", "의", "도"
    )

    /**
     * 조사로도 쓰이는 의존명사('만큼'·'뿐')에 쓰는 **좁은** 판정.
     *
     * 관형사형 어미 '-는'·'-은'이거나 받침이 ㄹ 일 때만 참이다. 받침 ㄴ 을 통째로
     * 받아 주면 '돈만큼'·'사람뿐' 같은 조사 자리를 갈라 버린다 — 조사일 때는 붙여
     * 쓰는 것이 맞으므로 그건 오교정이다.
     */
    private fun adnominalStrict(match: MatchResult): Boolean {
        val syllable = match.groupValues[1][0]
        return syllable == '는' || syllable == '은' || Hangul.jongseongOf(syllable) == 'ㄹ'
    }

    /** 규칙이 잡은 자리의 앞 두 음절(앞말 + 의존명사). 예외표를 볼 때 쓴다. */
    private fun head(match: MatchResult): String = match.value.take(2)

    /**
     * 받침이 ㄹ 이라 '-ㄹ 리(가)'로 보이지만 그냥 용언인 것들. '빨리 가'가 '빨 리가'가
     * 되는 것을 막는다 — 이 규칙이 낼 수 있는 가장 나쁜 실수다.
     */
    private val RI_EXCEPTIONS = setOf(
        "빨리", "멀리", "달리", "걸리", "물리", "불리", "살리", "알리", "올리", "흘리",
        "말리", "갈리", "몰리", "눌리", "실리", "팔리", "쏠리", "울리", "늘리", "들리",
        "밀리", "끌리", "헐리", "널리", "졸리", "쓸리", "찔리", "절리", "홀리", "얼리",
        "굴리", "돌리", "떨리", "벌리", "뿔리", "썰리", "쌀리", "짤리", "털리", "열리",
        "갈리", "찔리", "쏠리", "뚫리", "끓리", "잘리", "빨리", "쓸리", "닫히"
    )

    /**
     * 받침이 ㄹ 이라 '-ㄹ 만하다'로 보이지만 '체언 + 조사 만 + 하다'인 것들.
     * '일만 하고'가 '일 만하고'가 되는 것을 막는다.
     */
    private val MANHA_EXCEPTIONS = setOf(
        "일만", "물만", "술만", "글만", "말만", "별만", "딸만", "쌀만", "길만", "실만",
        "돌만", "절만", "꿀만", "탈만", "줄만", "굴만", "털만", "칼만", "달만", "불만"
    )

    /** '-ㄴ 대로'로 보이지만 조사 '대로'가 붙은 체언인 것들. */
    private val DAERO_EXCEPTIONS = setOf("말대", "절대", "뜻대", "본대", "제대", "맘대")

    /** '-ㄴ 건지'로 보이지만 '-건' 으로 끝나는 명사인 것들. */
    private val GEON_EXCEPTIONS = setOf("사건", "조건", "물건", "안건", "요건", "여건", "문건", "용건")

    private fun adnominalBefore(match: MatchResult): Boolean =
        Hangul.jongseongOf(match.groupValues[1][0]) in ADNOMINAL_JONG

    private fun rieulBefore(match: MatchResult): Boolean =
        Hangul.jongseongOf(match.groupValues[1][0]) == 'ㄹ'

    val DEFAULT: List<TextRule> = listOf(
        // 문장 부호 뒤에는 공백이 온다. ("네,저는" -> "네, 저는")
        // 앞뒤가 **둘 다 한글**일 때만 건드린다 — 숫자(1,000 / 3.14)를 피하려는 것이다.
        TextRule.of("""([가-힣][,.!?])([가-힣])""", "$1 $2", R),

        // 수관형사 + 단위 의존명사는 띄어 쓴다. ("네개야" -> "네 개야", "두명의" -> "두 명의")
        // **수관형사는 어절 첫머리에만 본다**(앞에 한글이 없을 때). 낱말 속에 우연히
        // 들어앉은 것을 수로 읽으면 '무한대로'가 '무한 대로'가 되고 '주십시오'가
        // '주십 시오'가 된다. 앞말이 붙어 있는 진짜 수량('책두 권')은 놓치지만,
        // 그건 디코더가 먼저 '책|두'를 가르면 이 규칙에 다시 걸린다.
        TextRule.of(
            """(?<![가-힣])(${NUMERALS.joinToString("|")})(${UNITS.joinToString("|")})""",
            "$1 $2",
            R
        ) { match -> match.value !in NUMERAL_EXCEPTIONS },

        // 보조용언 '-고 있다', '-지 않다/못하다/말다' 는 띄어 쓴다.
        // ("알고있다" -> "알고 있다", "쉽지않습니다" -> "쉽지 않습니다")
        TextRule.of("""([가-힣]고)(있|없|싶)""", "$1 $2", R),
        TextRule.of(
            """([가-힣]지)(않|못하|말고|말자|맙|마라|마세|말아|마(?![가-힣]))""",
            "$1 $2",
            R
        ) { match -> match.groupValues[1] !in JI_EXCEPTIONS },

        // 조사만 홀로 떨어져 나온 경우 앞말에 붙인다. ("학교 에서" -> "학교에서")
        // '와/과'는 명령형 '와'와, '밖에'는 명사 '밖'과 겹쳐서 뺐다.
        TextRule.of(
            """([가-힣])\s+(${PARTICLES.joinToString("|")})(?![가-힣])""",
            "$1$2",
            R
        ),

        // 의존명사 '수': 앞은 관형형 어미 ㄹ, 뒤는 '있/없'일 때만 띄운다.
        TextRule.of("""([가-힣])\s*수\s*밖에""", "$1 수밖에", R) { match ->
            rieulBefore(match) && (match.groupValues[1] + "수") !in SU_EXCEPTIONS
        },
        TextRule.of("""([가-힣])\s*수\s*(있|없)""", "$1 수 $2", R) { match ->
            rieulBefore(match) && (match.groupValues[1] + "수") !in SU_EXCEPTIONS
        },

        // 의존명사 '것'
        TextRule.of("""([가-힣])\s*것\s*같""", "$1 것 같", R) { match ->
            adnominalBefore(match) && (match.groupValues[1] + "것") !in GEOT_EXCEPTIONS
        },
        TextRule.of(
            """([가-힣])\s*것\s*(이다|이라|인가|일까|이야|입니다)""",
            "$1 것$2",
            R
        ) { match ->
            adnominalBefore(match) && (match.groupValues[1] + "것") !in GEOT_EXCEPTIONS
        },

        // 의존명사 '줄' ("할줄알아" -> "할 줄 알아")
        // '모르다'는 활용형이 갈려서('몰랐다') 어간만으로는 잡히지 않는다.
        TextRule.of(
            """([가-힣])\s*줄\s*(알|몰라|몰랐|모르|모른|모를)""",
            "$1 줄 $2",
            R,
            ::adnominalBefore
        ),

        // 의존명사 '둥' ("듣는둥마는둥" -> "듣는 둥 마는 둥")
        //
        // 언어모델이 '듣는둥'·'마는둥'을 **한 낱말로 알고 있어서** 디코더가 여기서 멈춘다.
        // 말뭉치에 붙여 쓴 형태가 그대로 들어가 있는 탓이다. 그래서 규칙으로 뗀다.
        //
        // **짝을 요구한다.** 이 말은 늘 '-는 둥 마는 둥' 처럼 둘이 붙어 다니고, '둥'으로
        // 끝나는 낱말이 잇달아 두 번 나오는 일은 이 관용구 말고는 없다. 앞이 관형형
        // 어미(받침 ㄹ/ㄴ)인 것까지 보면 규칙이 걸릴 자리가 사실상 이것뿐이 된다.
        //
        // 뒤에 '하다'가 붙는 꼴("...마는둥했다")을 먼저 놓는다. 나중 규칙이 같은 자리를
        // 다시 만나도 이미 띄어져 있어 결과가 바뀌지 않는다.
        TextRule.of(
            """([가-힣])\s*둥\s*(마는|말|만)\s*둥\s*(하|했|한|할)""",
            "$1 둥 $2 둥 $3",
            R,
            ::adnominalBefore
        ),
        TextRule.of(
            """([가-힣])\s*둥\s*(마는|말|만)\s*둥""",
            "$1 둥 $2 둥",
            R,
            ::adnominalBefore
        ),

        // ── 의존명사 ──────────────────────────────────────────────────────────
        //
        // 관형사형 어미(받침 ㄹ/ㄴ) 뒤의 의존명사는 띄어 쓴다. 통계로는 잘 안 되는
        // 자리다 — 말뭉치에 붙여 쓴 꼴이 그대로 들어 있어서 언어모델이 '할거야'를
        // 한 낱말로 알고 있고, 그러면 디코더가 거기서 멈춘다.
        //
        // 조건을 좁게 잡는 방식은 위의 '수'·'것'과 같다. 앞의 받침만 보지 않고
        // **뒤에 오는 것까지** 본다. 그래야 '-는데'(어미)와 '데'(의존명사)처럼
        // 겉모양이 같은 둘을 가를 수 있다.

        // '거' (것의 구어형). 뒤에 오는 말을 한정한다 — '볼거리'·'먹거리'를 피한다.
        TextRule.of("""([가-힣])거(야|예요|에요|였|였어|거든)""", "$1 거$2", R, ::adnominalBefore),

        // '게' (것이). '-ㄹ게'(어미)와 갈리려고 뒤에 오는 서술어를 요구한다.
        // '할게요'는 뒤가 '요'라 안 걸리고, '먹을 게 없어'는 걸린다.
        TextRule.of("""([가-힣])\s*게\s*(없|있|많|좋|아니|어때)""", "$1 게 $2", R, ::adnominalBefore),

        // '건지/건가' (것인지). '사건지'·'조건지' 같은 명사는 예외로 뺀다.
        TextRule.of("""([가-힣])건(지|가)""", "$1 건$2", R) { match ->
            adnominalBefore(match) && head(match) !in GEON_EXCEPTIONS
        },

        // '데' (곳·일). **조사가 붙었을 때만** 띄운다 — 조사를 못 받는 '-는데'(어미)와
        // 그것 하나로 갈린다. '그런데가'는 접속부사라 뒤돌아보기로 뺀다.
        TextRule.of("""([가-힣])(?<!그런)(?<!이런)(?<!저런)데(가|를)(?![가-힣])""", "$1 데$2", R, ::adnominalBefore),

        // '지' (그때부터 지금까지). 뒤에 기간을 재는 말이 올 때만.
        TextRule.of(
            """([가-힣])지(?=\s*(얼마|오래|한참|며칠|이틀|사흘|나흘|일주일))""",
            "$1 지",
            R
        ) { match -> Hangul.jongseongOf(match.groupValues[1][0]) == 'ㄴ' },

        // '만큼'·'뿐'. 조사로도 쓰이는 말이라 좁은 판정을 쓴다.
        TextRule.of("""([가-힣])만큼""", "$1 만큼", R, ::adnominalStrict),
        TextRule.of("""([가-힣])뿐(?=이|만|[^가-힣]|${'$'})""", "$1 뿐", R, ::adnominalStrict),

        // '바' (앞에서 말한 내용). 조사가 붙고, 그 뒤가 끊길 때만 — '물바가지'를 피한다.
        TextRule.of("""([가-힣])바(가|를|에|와)(?![가-힣])""", "$1 바$2", R, ::adnominalBefore),

        // '채' (그 상태 그대로). '입은 채로'.
        TextRule.of("""([가-힣])채로(?![가-힣])""", "$1 채로", R) { match ->
            Hangul.jongseongOf(match.groupValues[1][0]) == 'ㄴ'
        },

        // '척'·'체' (그런 듯이 꾸미는 것).
        TextRule.of("""([가-힣])(척|체)(하|도|만)""", "$1 $2$3", R, ::adnominalBefore),

        // '리' (까닭·이치). 용언 '빨리·멀리'와 겹쳐서 예외표가 길다.
        //
        // **'-리는'은 받지 않는다.** '열리는'·'걸리는'·'팔리는'처럼 피동 용언의 활용형이
        // 통째로 그 꼴이라, 조사 '는'까지 받아 주면 얻는 것보다 잃는 것이 많다
        // ('격주로 열리는' → '격주로 열 리는').
        TextRule.of("""([가-힣])리(가|도)(?![가-힣])""", "$1 리$2", R) { match ->
            rieulBefore(match) && head(match) !in RI_EXCEPTIONS
        },

        // '뻔하다' (그렇게 될 것 같았다). '뻔'으로 끝나는 말이 없어 안전하다.
        TextRule.of("""([가-힣])뻔(하|했|한)""", "$1 뻔$2", R, ::rieulBefore),

        // '만하다' (그럴 값어치가 있다). '일만 하고'와 겹쳐서 예외표를 본다.
        TextRule.of("""([가-힣])만(하|한|해|했|함)""", "$1 만$2", R) { match ->
            rieulBefore(match) && head(match) !in MANHA_EXCEPTIONS
        },

        // '중' (하는 동안). 좁은 판정 — '집중이'·'명중을'을 건드리지 않는다.
        TextRule.of("""([가-힣])중(이|인|에|을|은)""", "$1 중$2", R) { match ->
            adnominalStrict(match) && head(match) != "열중"
        },

        // '듯' 짝 ('올 듯 말 듯'). '둥'과 같은 이유로 짝을 요구한다.
        TextRule.of("""([가-힣])\s*듯\s*(말|안)\s*듯""", "$1 듯 $2 듯", R, ::adnominalBefore),

        // '대로' (그와 같이). 조사로도 쓰여서 예외표를 본다 — '맘대로'는 붙여 쓴다.
        TextRule.of("""([가-힣])대로(?![가-힣])""", "$1 대로", R) { match ->
            adnominalStrict(match) && head(match) !in DAERO_EXCEPTIONS
        },

        // 부사 '좀'. 앞뒤 어느 쪽에 붙어 와도 뗀다. '좀'으로 끝나는 낱말은 없고,
        // '좀'으로 시작하는 낱말은 '좀도둑'·'좀먹다' 둘뿐이라 그것만 피한다.
        TextRule.of("""([가-힣])좀(?![가-힣])""", "$1 좀", R),
        TextRule.of("""(?<![가-힣])좀(?![도먹])([가-힣])""", "좀 $1", R),

        // 부정의 '못'. **'못-'으로 시작하는 낱말만 피하면 된다** — '못하다·못되다·
        // 못나다·못살다·못생기다·못마땅하다·못지않다' 와 '못자리·못줄·못둑·못물'.
        // 어절 첫머리에서만 본다('연못이'가 '연 못이'가 되지 않게).
        //
        // **'하다'의 활용형을 통째로 뺀다.** '못했다'·'못한다'·'못합니다'는 '못하다'
        // 한 낱말이다. 처음에 '하' 만 빼 두었다가 격식체 1,000문장에서 오교정이
        // 0.8% → 2.8% 로 뛰었다 — '이해하지 못했다'가 죄다 '못 했다'가 됐다.
        TextRule.of("""(?<![가-힣])못(?![하한할함해했합되된될됨돼나난날살지자줄둑물생마미])([가-힣])""", "못 $1", R),

        // 부정의 '안'. **뒤에 올 수 있는 용언을 적어 둔 만큼만** 뗀다. '안'으로 시작하는
        // 낱말이 워낙 많아서('안내·안녕·안전·안경·안사람·안쓰럽다') 넓게 잡으면 바로
        // 망가진다. 여기 적힌 것은 '안' 뒤에 왔을 때 딴 낱말이 될 일이 없는 음절들이다.
        TextRule.of("""(?<![가-힣])안([가와해했먹봐받씻입열닫읽듣울웃믿잊찾놀갔왔봤잤샀])""", "안 $1", R),

        // 의존명사 '때문'은 앞말과 늘 띄고, 뒤의 조사와는 붙는다.
        TextRule.of("""([가-힣])\s*때문""", "$1 때문", R),

        // 의존명사 '때' ("먹을때" -> "먹을 때")
        TextRule.of("""([가-힣])때""", "$1 때", R) { match ->
            adnominalBefore(match) && match.value !in TTAE_EXCEPTIONS
        }
    )
}
