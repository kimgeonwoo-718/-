     * 이름·외래어(할리·줄리·빌리)와 부딪혀서 뒤에 '없다·있나·만무' 나 문장 끝이 올 때만.
     */
    private fun riNoun(match: MatchResult): Boolean {
        val prefix = match.groupValues[1]
        val syllable = match.groupValues[2][0]
        if (Hangul.jongseongOf(syllable) != 'ㄹ' || "${syllable}리" in RI_EXCEPTIONS) return false
        // 긴 말도 뒤에 '없다·있겠어·만무' 가 와야 한다(2026-10-13) — '버클리가·티볼리가·오클리가 개발한' 처럼 'ㄹ리' 로 끝나는
        // 외국 이름을 '버클 리가' 로 갈랐다(기사 말뭉치 26곳 중 25곳).
        val verb = when {
            prefix.isEmpty() -> syllable in RI_VERB_SHORT
            // '-릴' 은 '올리다·버리다' 처럼 '-리다' 용언일 때만 — '메이스트릴리'(이름)를 피한다.
            syllable == '릴' -> prefix.last() in RIL_STEMS
            else -> syllable in RI_VERB_LONG
        }
        return verb && RI_CUE.containsMatchIn(match.groupValues[4])
    }

