            """(?<![가-힣])(본|간|가본|해본|먹어본|들어본|만나본|써본|타본|입어본|살아본|읽어본|받아본|봤던|가봤던)적(이|은|도)?\s*(있|없)""",
            "$1 적$2 $3",
            R
        ),

        // 의존명사 '거' — 어절이 '-ㄴ거/-ㄹ거'로 **끝날 때**. '그런거 아니야' → '그런 거'.
        // 앞 음절을 관형사형으로 흔한 것만 적는다 — '근거'·'선거' 같은 명사를 피한다.
        TextRule.of(
            """(?<![가-힣])([가-힣]*(?:는|은|을|런|럴|떤|한|할|된|될|간|갈|온|올|본|볼|산|살|준|쓴|쓸|탄|탈|닌|뭔|인))거(지|죠|잖아|면|라고|라서|니까|든|도|냐|니|야|예요|에요|였어|였|거든)?(?![가-힣])""",
            "$1 거$2",
            R
        ),
        // '할 게 뭐 있어', '먹을 게 없어' — '-ㄹ게'(어미)와 갈리려고 뒤를 좁힌다.
        // 디코더가 '먹을게'를 잠깐 '먹을께'로 바꿔 두는 일이 있어 '께'도 받는다(어절 규칙이
        // 나중에 '께'를 '게'로 되돌린다).
        TextRule.of("""([가-힣])[게께](\s+)(뭐|없|있|많|너무|별로|딱히|하나도)""", "$1 게$2$3", R, ::rieulBefore),

        // 의존명사 '때문'은 앞말과 늘 띄고, 뒤의 조사와는 붙는다.
        TextRule.of("""([가-힣])\s*때문""", "$1 때문", R),

        // 의존명사 '때' ("먹을때" -> "먹을 때")
        TextRule.of("""([가-힣])때""", "$1 때", R) { match ->
            adnominalBefore(match) && match.value !in TTAE_EXCEPTIONS
        }
    )
}
