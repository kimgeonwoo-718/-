        if (Hangul.jongseongOf(syllable) != 'ㄴ' || syllable in JI_ASKING_SYLLABLES) return false
        val word = match.groupValues[1] + syllable
        if (word in JI_ASKING_WORDS || jiNoun(match.groupValues[1], syllable)) return false
