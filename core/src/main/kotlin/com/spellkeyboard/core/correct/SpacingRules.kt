    /** '지' 앞 음절이 관형형으로 끝나는가: '는'이거나 받침이 ㄴ·ㄹ. */
    private fun adnominalForJi(syllable: Char): Boolean =
        syllable == '는' || Hangul.jongseongOf(syllable).let { it == 'ㄴ' || it == 'ㄹ' }

