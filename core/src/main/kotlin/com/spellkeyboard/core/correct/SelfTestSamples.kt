package com.spellkeyboard.core.correct

/**
 * 설정 화면의 "교정 엔진 점검하기" 가 돌리는 표본.
 *
 * **core 에 두고 테스트로 못박는다.** 안드로이드 쪽에 기대값을 손으로 적어 두면,
 * 엔진은 멀쩡한데 점검만 FAIL 을 뱉는 일이 생긴다. 그러면 있지도 않은 버그를 쫓게
 * 되는데, 실기기 로그를 볼 수 없는 이 프로젝트에서 그건 하루를 통째로 날리는 일이다.
 *
 * 규칙·띄어쓰기·맞춤법 세 갈래를 골고루 넣는다 — 어느 갈래가 죽었는지 결과만 보고
 * 가릴 수 있어야 진단 도구다.
 */
object SelfTestSamples {

    /** 입력 → 기대 결과. */
    val ALL: List<Pair<String, String>> = listOf(
        // 규칙 사전
        "됬다" to "됐다",
        "왠만하면" to "웬만하면",
        "할께요" to "할게요",

        // 띄어쓰기 (형태소 사전)
        "할수있다" to "할 수 있다",
        "먹을때" to "먹을 때",
        "너때문에" to "너 때문에",
        "아버지가방에들어가신다" to "아버지 가방에 들어가신다",
        "오늘은날씨가좋아서기분이좋다" to "오늘은 날씨가 좋아서 기분이 좋다",

        // 맞춤법 (분석 비용 비교) — 규칙 목록에 없는 오타
        "안녕하새요" to "안녕하세요",
        "햇는대요" to "했는데요",

        // 멀쩡한 말은 그대로 둬야 한다
        "안녕하세요" to "안녕하세요",
        "감사합니다" to "감사합니다"
    )
}
