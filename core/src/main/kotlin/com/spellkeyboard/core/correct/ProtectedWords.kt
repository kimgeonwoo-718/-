package com.spellkeyboard.core.correct

/**
 * **고치지 않는 말.** 학교·대학 줄임말처럼 사전(언어모델)에는 없지만 틀린 말이 아닌 것들.
 *
 * ## 왜
 *
 * 사전에 없는 말은 교정기 눈에 "오타일지도 모르는 말" 이다. 그래서 가까운 아는 말로 바꿔 버렸다 —
 * '서울체고' → '서울최고', '과고 준비해' → '광고 준비해'(2026-10-06 사용자 제보). 학교 줄임말은
 * 학생이 제일 많이 치는 고유명사라 여기서 틀리면 바로 눈에 띈다.
 *
 * ## 어떻게
 *
 * 하나하나 적지 않고 **꼴로** 잡는다: (지명·학교 이름) + 계열 + 고/중/대/초 (+ 조사).
 * '서울체고', '부산예고', '대원외고', '과고', '한체대', '서울과고를' 이 다 걸린다.
 * 계열 글자(체·예·과·외·공·상·농·여·남 …) 뒤에 바로 고/중/대/초 가 와야 하므로 '최고'·'광고' 같은
 * 보통 낱말은 안 걸린다. 걸리면 그 어절은 **아무 교정도 안 한다** — 놓치는 것은 '과고'(광고의 오타)
 * 같은 드문 경우뿐이고, 학교 이름을 망가뜨리는 것보다 낫다. '상대'·'예고'·'체중' 처럼 꼴이 같은 보통 낱말도
 * 걸리지만 그 자체로 맞는 말이라 안 고쳐도 손해가 없다. 계열 글자를 한 글자짜리로 더 넓히지는 마라 —
 * '사·교·의·한' 을 넣었더니 '사고'·'한대' 처럼 흔한 말까지 잡혔다.
 *
 * 쓰는 곳: 문맥 교정기([com.spellkeyboard.core.lm.ContextCorrector]), 폰의 Kiwi 오타 교정기(아는 말 문지방).
 */
object ProtectedWords {

    /** 학교 계열. 긴 것부터 — 정규식은 왼쪽 선택지부터 시도한다. */
    private val TRACKS = listOf(
        "마이스터", "특성화", "외국어", "자율형", "과학", "예술", "체육", "국제", "자사", "특목", "영재",
        "디자인", "미술", "음악", "국악", "조리", "관광", "정보", "항공", "해양", "간호", "여자", "남자",
        "체", "예", "과", "외", "공", "상", "농", "여", "남"
    )

    /** 학교 줄임말 뒤에 붙는 조사·서술어. 이것까지 붙은 어절도 같은 말로 본다. */
    private val TAILS = listOf(
        "에서는", "이에요", "입니다", "이라서", "이라고", "이었어", "였어", "이야", "이랑", "에서", "까지", "부터",
        "으로", "로", "이", "가", "은", "는", "을", "를", "에", "의", "도", "만", "랑", "야", "생", "라"
    )

    private val SCHOOL = Regex(
        "^[가-힣]{0,6}?(?:${TRACKS.joinToString("|")})(?:고|중|대|초)(?:등학교|학교)?" +
            "(?:${TAILS.joinToString("|")})?$"
    )

    /** [word] 가 고치지 말아야 할 말인가. 앞뒤 문장 부호·장식은 떼고 본다. */
    fun isProtected(word: String): Boolean {
        val core = word.trim { it !in '가'..'힣' }
        if (core.length < 2) return false
        return SCHOOL.matches(core)
    }
}
