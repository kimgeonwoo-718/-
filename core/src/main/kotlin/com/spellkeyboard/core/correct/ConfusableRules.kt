            m.groupValues[1] + "졸" + when (m.groupValues[2]) { "려" -> "여"; "렸" -> "였"; "린" -> "인"; "릴" -> "일"; else -> "이" }
        },
        TextRule.computed("""(?<![가-힣])((?:생선|감자|고등어|갈치|연근|우엉|두부|메추리알|꽁치|코다리|장조림)(?:을|를)?\s*)졸(여|였|인|일|이)""", R) { m ->
