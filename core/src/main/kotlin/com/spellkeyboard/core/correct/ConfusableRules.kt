package com.spellkeyboard.core.correct

/**
 * **소리가 같거나 비슷해 헷갈리는 말**을 문맥으로 가른다 — 낫다/낳다, 로서/로써, 맞추다/맞히다 …
 *
 * ## 왜
 *
 * 사용자 제보(2026-10-09): '이게 낳을까 저게 낳을까' 를 못 고친다. 시험지 150문장으로 재 보니 '낳→낫' 25개 중 5개,
 * '나→낳' 12개 중 2개만 고쳤다. 이 말들은 낱말 하나만으로는 못 가린다 — 뜻을 알아야 한다. 그래서 [SpellingRules] 머리말은
 * 일부러 뺐었다("오교정 한 번이 미교정 열 번보다 나쁘다"). 이 파일은 그 원칙을 **버리지 않고** 한 걸음 나간다:
 *
 *  - **문맥 단서가 분명한 자리만** 고친다. 단서가 없거나 두 뜻이 다 될 수 있으면 그대로 둔다.
 *  - 단서는 **이미 친 앞말**에서만 구한다. 실시간으로는 뒤에 올 말을 못 본다(전체 교정에서는 보지만 거기에 기대지 않는다).
 *  - 고치는 방향이 한쪽으로 굳은 꼴만 본다 — '낫을까' 는 낫(풀 베는 연장)이 아니라 거의 언제나 '나을까' 다.
 *
 * 값은 각 규칙 옆에 적었다. 시험지는 `tools/localcheck/live/confusables.tsv`(고쳐야 하는 것 + **그대로 둬야 하는 것**).
 * 그대로 둬야 하는 쪽이 더 중요하다: 이 규칙들이 멀쩡한 글을 건드리면 안 된다.
 *
 * ## 못 하는 것
 *
 *  - '정답을 맞췄어'(답을 서로 맞춰 봤다 ↔ 맞혔다), '생각이 틀려'(내 생각이 틀렸다 ↔ 서로 다르다), '하는대'(들은 말 ↔ 연결),
 *    '이 방법으로서'(자격 ↔ 수단)는 두 뜻이 다 된다. 문맥 단서가 없으면 그대로 둔다.
 */
object ConfusableRules {

    private const val R = "맞춤법"

    // ── 낫다 / 낳다 ───────────────────────────────────────────────────────────────────────────────────────────
    //
    // 낫다(병이 낫다, 더 낫다)는 ㅅ 불규칙이라 모음 어미 앞에서 ㅅ 이 빠져 '나을·나아·나았' 이 되고, 자음 어미 앞에서는
    // '낫지·낫다·낫네' 다. 낳다(아이를 낳다, 결과를 낳다)는 어느 쪽에서나 '낳' 이다. 그래서 '낳을까' 가 '나을까' 인지는
    // 어미가 아니라 **누가 주어이고 무엇을 하는가**로 갈린다.

    /** 낫다의 모음 어미(ㅅ 이 빠진다). 낫다 꼴로 읽을 때 '나' 뒤에 붙는 것. */
    private const val NA_VOWEL_TAIL =
        "(?:을까요?|을지|을래요?|아서|아도|아야|아요?|았(?:어요?|다|네요?|지요?|는데|을까|으면)|으면|으니까|으세요" +
            "|은(?=\\s+(?:것|거|건|듯|편))|을(?=\\s+(?:것|거|듯|텐데|때)))(?![가-힣])"

    /** 낫다의 자음 어미. 낫다 꼴로 읽을 때 '낫' 뒤에 붙는 것. */
    private const val NA_CONSONANT_TAIL = "(?:지요?|다|네요?|겠(?:다|어|네|지|는데)?|냐|죠|구나|군|거든)(?![가-힣])"

    private const val NA_ANY_TAIL = "(?:$NA_VOWEL_TAIL|$NA_CONSONANT_TAIL)"

    /**
     * 비교하는 부사('더·훨씬')가 이미 있을 때 쓰는 꼬리. '낳은·낳을' 이 홀로 와도 낫다로 본다 — '이게 더 낳은 결과'(이것이 더
     * 많이 빚어낸)는 '이게 더 나은 결과'(더 좋은)에 비해 거의 안 쓴다. 실시간 교정은 앞 세 어절만 봐서 뒤의 '것 같아' 를
     * 기다릴 수 없는데, '더' 가 있으면 기다릴 이유가 없다.
     */
    private const val NA_OPEN_TAIL = "(?:$NA_ANY_TAIL|[은을](?=\\s|$))"

    /** 낫다 꼴로 고친 글: 모음 어미면 '나', 자음 어미면 '낫'. */
    private fun asNatda(prefix: String, tail: String): String {
        val consonantFirst = tail.firstOrNull()?.let { it in "지다네겠냐죠구군거" } == true
        return prefix + (if (consonantFirst) "낫" else "나") + tail
    }

    /** 아픈 곳·병. 앞에 오면 '낳' 은 거의 언제나 '낫' 이다. */
    private const val ILLNESS =
        "감기|병|상처|몸살|두통|배탈|독감|코로나|장염|비염|목감기|허리|무릎|어깨|기침|통증|염증|멍|흉터|증상|아픈\\s*곳|몸|열|배|머리|목|팔|다리|피부|상태"

    /**
     * 아픈 곳과 '낳' 사이에 낄 수 있는 말. **정도·때 부사만** 받는다. 아무 말이나 받으면 '몸이 안 좋아서 일찍 낳았어'(목적어를
     * 줄인 출산)가 '나았어' 로 바뀐다.
     */
    private const val DEGREE_ADVERB =
        "다|좀|조금|많이|거의|벌써|이제|금방|싹|완전히|이미|빨리|아직|안|못|잘|훨씬|겨우|드디어|곧|바로|얼른|서서히|점점"

    private const val BIRTH_OBJECT =
        "아이|아이들|애|애들|아기|아가|아들|딸|자식|새끼|새끼들|쌍둥이|손주|손자|손녀|첫째|둘째|셋째|막내|알|송아지|강아지|병아리"

    private const val PRODUCE_OBJECT =
        "결과|결과물|비극|오해|논란|문제|사고|부작용|결실|성과|효과|파장|결말|참사|갈등|혼란|폐해|불씨|기적|변화|이익|수익|열매|악순환|오류|후유증|파문|반향"

    /**
     * 낳다 꼴로 읽을 때 '나' 뒤에 붙는 어미 — 타이핑이 '나' 로 간 것. 홀로 선 '아'(낳아)는 뺀다: 실시간 교정은 뒤에 올 말을 못
     * 보는데, '나아 보이다'(좋아 보이다)는 낫다라 '결과를 더 나아 보이게' 가 '낳아' 로 바뀐다(실제로 그랬다).
     */
    private const val NAH_TAIL_CORE =
        "(?:을까요?|을지|을래요?|을(?=\\s+(?:거|것|수|계획|예정|생각|때|텐데|듯))|았(?:어요?|다|네요?|대|지요?|는데|으면)|아서|아도|아야" +
            "|으면|으니까?|으려|으며|은(?=\\s+(?:엄마|아빠|사람|여자|부모|뒤|후|거|것)))"

    /** 목적어가 아이·새끼·알이면 홀로 선 '아'(아이를 낳아)도 받는다. 낫다는 목적어를 안 받아 '나아 보이다' 와 겹치지 않는다. */
    private const val NAH_TAIL_BIRTH = "(?:$NAH_TAIL_CORE|아(?![가-힣])(?!\\s*보[이여]))(?![가-힣])"

    private const val NAH_TAIL_PRODUCE = "$NAH_TAIL_CORE(?![가-힣])"

    val RULES: List<TextRule> = listOf(
        // 낫다 ― 이미 풀린 어미 '낳아지다' 는 없는 말이다. '나아지다'(좋아지다)다.
        TextRule.of("""낳아(지|져|졌|진)""", "나아$1", R),

        // 낫다 ― '이게·저게·그게·뭐가·하는 게' 가 주어면 "무엇이 더 나은가" 다. 낳다의 주어는 사람·짐승이라 '게'(것이)가 못 온다.
        // 다만 '이게 낳은 결과'(이것이 빚어낸)는 맞는 말이라 **관형형(은·을)은 뒤에 '것·거·듯…' 이 올 때만** 본다.
        TextRule.computed(
            """((?:[이저그]게|뭐가|어느\s*게|어떤\s*게|는\s+게|[이그저]\s*(?:쪽|방법|방식|선택|길)[이가]|(?:쪽|방법|방식|선택|편)[이가])(?:\s+(?:더|훨씬|한결|훨))?\s*)낳($NA_ANY_TAIL)""",
            R
        ) { m -> asNatda(m.groupValues[1], m.groupValues[2]) },
        // 낫다 ― 위와 같되 '더·훨씬' 이 있으면 꼬리를 열어 준다. 실시간 창은 세 어절이라 '어느 게 더 낳아' 에서 '어느' 가 잘리므로 홀로 선
        // '게' 도 여기서만 받는다('게 더 낳아'). 게(蟹)가 '더' 와 함께 새끼를 낳는 문장은 거의 없다.
        TextRule.computed(
            """((?:(?<![가-힣])게|[이저그]게|뭐가|어느\s*게|어떤\s*게|는\s+게|[이그저]\s*(?:쪽|방법|방식|선택|길)[이가]|(?:쪽|방법|방식|선택|편)[이가])\s+(?:더|훨씬|한결|훨)\s*)낳($NA_OPEN_TAIL)""",
            R
        ) { m -> asNatda(m.groupValues[1], m.groupValues[2]) },

        // 낫다 ― '~보다 낳아', '~보다는 내가 낳지'. 비교하는 말 바로 뒤. 사이에 목적어('아이를')가 끼면 낳다라 건드리지 않는다.
        TextRule.computed(
            """(보다(?:는|도|야)?\s*(?:[가-힣]+(?<![을를])\s+)?)낳($NA_ANY_TAIL)""",
            R
        ) { m -> asNatda(m.groupValues[1], m.groupValues[2]) },

        // 낫다 ― '훨씬·한결·그나마·오히려 (더) 낳'. '더' 만으로는 '하나 더 낳을까'(아이)와 못 가려 뺐다.
        TextRule.computed(
            """((?:훨씬|한결|그나마|오히려)\s+(?:더\s+)?)낳($NA_OPEN_TAIL)""",
            R
        ) { m -> asNatda(m.groupValues[1], m.groupValues[2]) },

        // 낫다 ― 아픈 곳·병이 주어. 사이에 부사('아직 안')는 둘까지 허용하되, 목적어('~를')가 끼면 낳다다
        // ('병이 있는데도 아이를 낳았다').
        TextRule.computed(
            """((?:$ILLNESS)(?:가|이|는|은|도)?\s+(?:(?:$DEGREE_ADVERB)\s+){0,2})낳($NA_VOWEL_TAIL)""",
            R
        ) { m -> asNatda(m.groupValues[1], m.groupValues[2]) },

        // 낫다 ― 'ㅅ' 을 어미 앞에 그대로 둔 '낫았어·낫아·낫을까·낫으면' 은 없는 꼴이다. 낫(연장)의 조사 '을·은·으로' 는 건드리지 않는다.
        TextRule.of("""(?<![가-힣])낫(았|아서|아도|아야|으면|으니|을까|을지)""", "나$1", R),
        TextRule.of("""(?<![가-힣])낫아(?=$|[^가-힣]|요)""", "나아", R),

        // 낳다 ― 목적어가 아이·새끼·알이면 '나았다' 가 아니라 '낳았다' 다. 낫다는 목적어를 안 받는다.
        TextRule.computed(
            """((?:$BIRTH_OBJECT)(?:을|를)\s*(?:[가-힣]+(?<![을를])\s+)?)나($NAH_TAIL_BIRTH)""",
            R
        ) { m -> m.groupValues[1] + "낳" + m.groupValues[2] },
        // 낳다 ― 목적어가 결과·오해·논란처럼 빚어진 것이면 마찬가지.
        TextRule.computed(
            """((?:$PRODUCE_OBJECT)(?:을|를)\s*(?:[가-힣]+(?<![을를])\s+)?)나($NAH_TAIL_PRODUCE)""",
            R
        ) { m -> m.groupValues[1] + "낳" + m.groupValues[2] },

        // ── 로서 / 로써 ───────────────────────────────────────────────────────────────────────────────────────
        // '로서'는 자격(학생으로서), '로써'는 수단(칼로써)이다. 앞말이 **사람·역할**이면 자격, **연장·말·힘**이면 수단이다.
        // '모형으로써'(수단)가 '형' 에 걸리지 않게 앞이 한글이면 안 본다.
        TextRule.computed("""(?<![가-힣])($ROLE)(으로써|로써)""", R) { m ->
            m.groupValues[1] + (if (m.groupValues[2] == "으로써") "으로서" else "로서")
        },
        TextRule.computed("""(?<![가-힣])($MEANS)(으로서|로서)""", R) { m ->
            m.groupValues[1] + (if (m.groupValues[2] == "으로서") "으로써" else "로써")
        },
        // 앞말만으로는 못 가리는 '방법으로서' 는 뒤에 푸는 말이 오면 수단이다. 전체 교정에서만 보인다.
        TextRule.of("""(방법|방식|수단)으로서(\s+)(?=(?:해결|해소|극복|해냈|이뤘|풀|표현|증명|설명|막|이겨|달성))""", "$1으로써$2", R),

        // ── 든 / 던 ───────────────────────────────────────────────────────────────────────────────────────────
        // '-든'은 고르는 말('가든 말든'), '-던'은 지난 일을 떠올리는 말('먹던 음식')이다. 뒤에 곧바로 명사가 오는 '먹든 음식' 은 틀린
        // 꼴이지만 '뭘 하든 집에 가자'(고르는 말 + 새 절)와 겹치므로 **지난 일을 떠올리는 말이 앞에 있을 때만** 본다.
        TextRule.of(
            """((?:어릴\s*때|예전에|옛날에|그때|전에|어제|아까|늘|자주|항상|평소|원래|오랫동안|지난|작년|그동안)\s+(?:[가-힣]+\s+)?)($RECALL_STEM)든(\s+)($RECALL_NOUN)""",
            "$1$2던$3$4",
            R
        ),

        // ── 맞추다 / 맞히다 ───────────────────────────────────────────────────────────────────────────────────
        // '맞히다'는 정답·과녁을 **맞게 하다**, '맞추다'는 **서로 맞게 하다**(퍼즐·시간·박자). 목적어로 가른다.
        // '정답을 맞췄어'(서로 답을 맞춰 봤다)는 두 뜻이 다 돼서 뺐고, '맞춰' 꼴도 건드리지 않는다('문제를 맞춰 보자').
        TextRule.computed(
            """((?:문제|퀴즈|과녁|표적|범인)(?:을|를)\s*)맞(췄|춘|출|추는|추었)""",
            R
        ) { m -> m.groupValues[1] + "맞" + m.groupValues[2].replace("추", "히").replace("췄", "혔").replace("춘", "힌").replace("출", "힐") },
        TextRule.computed(
            """((?:퍼즐|시간|박자|호흡|눈높이|초점|알람|시계|균형|순서|템포)(?:을|를)\s*)맞(혔|힌|힐|히는|히고|히면|혀)""",
            R
        ) { m -> m.groupValues[1] + "맞" + m.groupValues[2].replace("히", "추").replace("혔", "췄").replace("힌", "춘").replace("힐", "출").replace("혀", "춰") },

        // ── 부치다 / 붙이다 ───────────────────────────────────────────────────────────────────────────────────
        // '부치다'는 우편·택배·짐을 **보내다**, '붙이다'는 **떨어지지 않게 하다**(우표·스티커). 목적어가 바로 앞에 올 때만 본다.
        // '벽에 편지를 붙였다'(붙이다)를 피하려고 앞에 '~에' 가 있으면 안 본다. '전을 부쳤다'(부침개)는 목록에 없다.
        TextRule.computed("""(?<!에\s)(?<!에다\s)((?:편지|택배|소포|엽서|우편|등기|팩스|짐)(?:을|를)\s*)붙(였|이|인|일|여)""", R) { m ->
            m.groupValues[1] + "부" + m.groupValues[2].replace("였", "쳤").replace("이", "치").replace("인", "친").replace("일", "칠").replace("여", "쳐")
        },
        TextRule.computed("""((?:우표|스티커|포스터|테이프|딱지|반창고|파스|벽보|전단지|메모지|포스트잇|벽지|타일|접착제)(?:을|를)\s*)부(쳤|치|친|칠|쳐)""", R) { m ->
            m.groupValues[1] + "붙" + m.groupValues[2].replace("쳤", "였").replace("치", "이").replace("친", "인").replace("칠", "일").replace("쳐", "여")
        },

        // ── 가리키다 / 가르치다 ───────────────────────────────────────────────────────────────────────────────
        // '가르키다'는 없는 말이다. 손짓·방향이면 '가리키다'(손가락으로 가리켰다), 배우는 것이면 '가르치다'(영어를 가르친다).
        // '가르키' 는 표에서 '가리키' 로 먼저 바뀌므로, 배우는 것 앞에서는 둘 다 받는다.
        TextRule.computed(
            """((?:$TEACH_OBJECT)(?:을|를)\s*(?:[가-힣]+(?<![을를])\s+)?)가(?:르|리)(켰|켜|킨|킬|키)""",
            R
        ) { m -> m.groupValues[1] + "가르" + m.groupValues[2].replace("켰", "쳤").replace("켜", "쳐").replace("킨", "친").replace("킬", "칠").replace("키", "치") },
        TextRule.of(
            """((?:손가락|손짓|막대기|화살표|바늘|시계|나침반|지도|화살|지팡이|리모컨)(?:으로|이|가|을|를)?\s*(?:[가-힣]+\s+)?)가르(켰|켜|킨|킬|키)""",
            "$1가리$2",
            R
        ),

        // ── 틀리다 / 다르다 ───────────────────────────────────────────────────────────────────────────────────
        // '틀리다'는 **맞지 않다**(답이 틀렸다), '다르다'는 **같지 않다**(성격이 다르다). 성격·취향·맛처럼 **원래 정답이 없는** 말이
        // 주어면 '다르다'다. '답이 틀려'·'스펠링이 틀렸어' 는 그대로 두고, '생각이 틀려'(내 생각이 틀렸다)도 뺀다.
        TextRule.computed(
            """((?:$DIFFER_SUBJECT)(?:이|가|은|는|도)?\s+(?:(?:너무|완전히|많이|좀|꽤|아주|서로|전혀|조금|약간|엄청|확실히|정말|진짜)\s+)?)틀(려|렸|리|린|릴)""",
            R
        ) { m -> m.groupValues[1] + differ(m.groupValues[2]) },
        TextRule.computed("""(서로\s+(?:[가-힣]+(?<![을를])\s+)?)틀(려|렸|리|린|릴)""", R) { m ->
            m.groupValues[1] + differ(m.groupValues[2])
        },

        // ── 늘리다 / 늘이다 ───────────────────────────────────────────────────────────────────────────────────
        // '늘리다'는 **많아지게**(체중·인원·예산), '늘이다'는 **길어지게**(고무줄·엿가락). 목적어로 가른다.
        TextRule.computed("""((?:$INCREASE_OBJECT)(?:을|를)\s*(?:[가-힣]+(?<![을를])\s+)?)늘(였|이|인|일|여)""", R) { m ->
            m.groupValues[1] + "늘" + m.groupValues[2].replace("였", "렸").replace("이", "리").replace("인", "린").replace("일", "릴").replace("여", "려")
        },
        TextRule.computed("""((?:고무줄|엿가락|밧줄|용수철|스프링|끈|엿)(?:을|를)\s*)늘(렸|리|린|릴|려)""", R) { m ->
            m.groupValues[1] + "늘" + m.groupValues[2].replace("렸", "였").replace("리", "이").replace("린", "인").replace("릴", "일").replace("려", "여")
        },

        // ── 한참 / 한창 ───────────────────────────────────────────────────────────────────────────────────────
        // '한참'은 **오랫동안**(한참 기다렸다), '한창'은 **가장 활발한 때**(한창 바쁘다). 뒤따르는 말로 가른다.
        TextRule.of("""한참(\s+)(?=(?:바쁜|자랄|클|피는|좋을|젊은|예쁠|공부할|놀|일할|뛰어놀|인기|유행|성수기|절정|무르익|진행|사춘기|활동|연애))""", "한창$1", R),
        TextRule.of("""(공사|작업|준비|공부|연습|농사|성수기|사춘기|여름|겨울|파티|축제|회의|수업)(가|는|도)?(\s*)한참(?=이|인|입)""", "$1$2$3한창", R),
        TextRule.of("""한창(\s+)(?=(?:걸렸|걸려|걸리|기다렸|기다려|웃었|울었|헤맸|찾았|걸었|뛰었|떠들었|쉬었|지났|뒤에|후에|동안|전에))""", "한참$1", R)
    )

    /** 틀리다 → 다르다. '틀려'→'달라', '틀렸'→'달랐', '틀리'→'다르', '틀린'→'다른', '틀릴'→'다를'. [tail] 은 '틀' 뒤의 한 글자. */
    private fun differ(tail: String): String = when (tail) {
        "려" -> "달라"
        "렸" -> "달랐"
        "리" -> "다르"
        "린" -> "다른"
        "릴" -> "다를"
        else -> "틀$tail"
    }

    /** 자격을 나타내는 사람·역할 말. 앞에 오면 '으로써' 는 '으로서' 다. */
    private const val ROLE =
        "학생|부모님|부모|엄마|아빠|아버지|어머니|선생님|선생|친구|사람|어른|아이|여자|남자|남편|아내|형|누나|오빠|언니|동생|팀장|대표|리더|회원|국민|시민|한국인|인간|주인|가족|보호자|고객|소비자|운전자|개발자|학부모|담당자|책임자|관리자|직원|사원|부장|과장|교사|의사|간호사|군인|경찰|아들|딸|제자|후배|선배|여성|남성|청소년"

    /** 수단을 나타내는 연장·말·힘. 앞에 오면 '으로서' 는 '으로써' 다. */
    private const val MEANS =
        "칼|가위|망치|열쇠|말|글|행동|노력|웃음|눈물|대화|투표|연필|펜|불|물|손|입|힘|몸"

    /** 지난 일을 떠올리는 '-던' 앞의 동사 어간. */
    private const val RECALL_STEM = "먹|살|입|쓰|보|듣|읽|마시|다니|놀|지내|보내|만나|타|하|사|두|넣|걸|신|끼"

    /** '-던' 뒤에 와서 '먹던 음식' 처럼 굳은 구체적인 명사. 사람은 뺐다('뭘 하든 사람은…'). */
    private const val RECALL_NOUN = "음식|곳|집|책|옷|물건|학교|동네|자리|노래|게임|영화|드라마|가방|신발|장난감|방|자전거|핸드폰|폰"

    /** 배우고 가르치는 것. 앞에 오면 '가르키·가리키' 는 '가르치' 다. 사람은 뺐다('학생을 가리켰다'는 맞는 말이다). */
    private const val TEACH_OBJECT = "영어|수학|국어|과학|피아노|기타|한글|춤|노래|요리|코딩|중국어|일본어|한국어|바이올린|수영|태권도|운동"

    /** 성격·취향·맛처럼 원래 정답이 없는, '다르다' 의 주어. '생각·의견·기억·답' 은 틀릴 수 있어서 뺐다. */
    private const val DIFFER_SUBJECT =
        "성격|취향|입맛|스타일|방식|느낌|분위기|색깔|색|모양|맛|목소리|얼굴|나이|키|버전|수준|차이|생김새|사고방식|가치관|취미|습관|말투|옷차림|디자인|가격|크기|무게|개성|문화|환경|처지|입장"

    /** 많아지게 하는 것. 앞에 오면 '늘이' 는 '늘리' 다. */
    private const val INCREASE_OBJECT =
