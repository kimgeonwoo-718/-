            R
        ) { match -> match.groupValues[1].isNotEmpty() || LOST_CUE.containsMatchIn(match.groupValues[4]) },

        // ── 반드시 / 반듯이 (2026-10-13) ──────────────────────────────────────────────────────────────────────
        // '반듯이' 는 **기울지 않게**(반듯이 눕다·앉다·접다·자라다), '반드시' 는 **꼭**. 뒤에 몸가짐·모양과 상관없는, 꼭 해야 하는 일이
        // 올 때만 고친다. 앞에 '자세·허리·글씨' 처럼 모양을 말하는 것이 있으면 그대로 둔다('자세를 반듯이 해야 해').
