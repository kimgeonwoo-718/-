            """(?<![가-힣])((?:[가-힣]+\s+)?)반듯이(\s+)(?=(?:$CERTAIN_NEXT))""",
            "$1반드시$2",
            R
        ) { match -> !SHAPE_BEFORE.containsMatchIn(match.groupValues[1]) },

        // ── 띄다 / 띠다 (2026-10-13) ──────────────────────────────────────────────────────────────────────────
        // '눈에 띄다'(뜨이다)를 '눈에 띠다' 로. 거꾸로 '미소를 띠다'·'붉은빛을 띠다'(지니다)를 '띄다' 로.
