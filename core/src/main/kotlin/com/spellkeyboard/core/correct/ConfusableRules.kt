        val last = word.last()
        return last == '의' || last == '적' || last == '는' || last == '던' ||
            Hangul.jongseongOf(last) == 'ㄴ' || Hangul.jongseongOf(last) == 'ㄹ'
    }

    /** 틀리다 → 다르다. '틀려'→'달라', '틀렸'→'달랐', '틀리'→'다르', '틀린'→'다른', '틀릴'→'다를'. [tail] 은 '틀' 뒤의 한 글자. */
