    /** '벌이다'(일을 차려 시작하다)의 목적어. */
    private const val EVENT_NOUN =
        "일|사업|잔치|싸움|판|소동|난리|굿|굿판|행사|파티|논쟁|전쟁|전투|술판|술자리|공사|시위|농성|캠페인|토론|협상|수사|작업|투쟁|경쟁|대결|" +
