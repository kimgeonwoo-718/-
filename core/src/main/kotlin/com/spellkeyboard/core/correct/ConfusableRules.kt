        ) { m -> m.groupValues[1] + when (m.groupValues[2]) { "띈" -> "띤"; "띌" -> "띨"; else -> "띠" } },

        // ── 벌이다 / 벌리다 (2026-10-13) ──────────────────────────────────────────────────────────────────────
        // '벌이다' 는 일을 **차려 시작하다**(잔치를 벌이다·싸움을 벌이다), '벌리다' 는 **사이를 넓히다**(입을 벌리다·격차를 벌리다).
