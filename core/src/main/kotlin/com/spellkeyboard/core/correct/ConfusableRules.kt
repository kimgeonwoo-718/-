    /** '잃어버리다' 가 분명한 뒷말 — 찾았다·잃어버린 것을 신고했다·새로 샀다(2026-10-13). */
    private val LOST_CUE = Regex("""찾|분실|신고|주웠|주운|새로\s*샀|새로\s*사|도둑|훔쳐|재발급|어디\s*갔|어디\s*있""")

    /** 들고 다니다가 잃어버리기 쉬운 것. '우산·안경·가방' 은 '두고 왔다' 로 더 자주 써서 뺐다. */
