                "띠였", "띠었" -> "띄었"
                "띤" -> "띈"
                "띨" -> "띌"
                else -> "띄"
            }
        },
        TextRule.computed(
            """((?:미소|웃음|빛|색|색깔|색채|성격|성향|경향|특징|특성|임무|사명|기운|열기|활기|생기|홍조|붉은빛|푸른빛|노란빛|윤기|광택|물기)(?:을|를)\s*)(띄(?=고|어|었|는|게|며|지|니|던|다)|띈|띌)""",
