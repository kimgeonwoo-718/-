            R
        ) { m ->
            m.groupValues[1] + "벌" + when (m.groupValues[2]) { "렸" -> "였"; "려" -> "여"; "리" -> "이"; "린" -> "인"; else -> "일" }
        },

        // ── 졸이다 / 조리다 · 썩이다 / 썩히다 · 저리다 / 절이다 (2026-10-13) ──────────────────────────────────────
        // 마음은 '졸이다'(마음을 졸이며), 생선·감자는 '조리다'(간장에 조리다).
