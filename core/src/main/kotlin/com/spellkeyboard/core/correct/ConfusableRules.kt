        "지갑|핸드폰|휴대폰|휴대전화|폰|스마트폰|열쇠|차키|카드|신용카드|체크카드|교통카드|여권|신분증|주민등록증|면허증|학생증|에어팟|이어폰|목걸이|반지|귀걸이|시계|노트북|자전거"

    /** '반듯이' 뒤에 오면 '반드시'(꼭)로 읽히는 말. 몸가짐·모양을 바로잡는 말('앉·눕·서·펴·접·써·해·살·돌려·다시')과 '돼·될'(반듯이 됐다)은 없다. */
