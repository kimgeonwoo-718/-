        // ── 쌓이다 / 싸이다 (2026-10-13) ──────────────────────────────────────────────────────────────────────
        // 스트레스·눈·일은 '쌓이다'. '싸이다'(보자기에 싸이다)와 갈리게 쌓이는 것이 주어로 바로 앞에 있을 때만.
